const fs = require("fs");
const path = require("path");
const { pathToFileURL } = require("url");
const esbuild = require("esbuild");

function splitIntoChunks(content, chunkSize) {
  const chunks = [];
  for (let i = 0; i < content.length; i += chunkSize) {
    chunks.push(content.slice(i, i + chunkSize));
  }
  return chunks;
}

function toCppHeader(scriptContent) {
  const rawDelimiter = "SM_MAP_JS";
  const chunkSize = 4 * 1024;
  const scriptChunks = splitIntoChunks(scriptContent, chunkSize);
  const literalExpression = scriptChunks
    .map((chunk) => `LR"${rawDelimiter}(${chunk})${rawDelimiter}"`)
    .join("\n    ");

  return `#pragma once

#include "vendor/std.hpp"

// Auto-generated map injection script header
// DO NOT EDIT - This file is generated by scripts/generate-map-injection-cpp.js

namespace extensions::infinity_nikki::generated {

constexpr std::wstring_view map_bridge_script =
    ${literalExpression};

}  // namespace extensions::infinity_nikki::generated
`;
}

async function main() {
  const projectRoot = path.resolve(__dirname, "..");
  const sourceEntry = path.join(
    projectRoot,
    "web",
    "src",
    "features",
    "map",
    "injection",
    "source",
    "index.js"
  );
  const generatedHeaderPath = path.join(
    projectRoot,
    "src",
    "extensions",
    "infinity_nikki",
    "generated",
    "map_injection_script.hpp"
  );

  if (!fs.existsSync(sourceEntry)) {
    throw new Error(`Map injection source entry not found: ${sourceEntry}`);
  }

  const sourceModule = await import(pathToFileURL(sourceEntry).href);
  if (typeof sourceModule.buildMapBridgeScriptTemplate !== "function") {
    throw new Error("buildMapBridgeScriptTemplate() is missing in injection source entry.");
  }

  const bridgeTemplate = sourceModule.buildMapBridgeScriptTemplate();
  const minified = esbuild.transformSync(bridgeTemplate, {
    loader: "js",
    minify: true,
  });

  const scriptContent = minified.code.trim();
  fs.mkdirSync(path.dirname(generatedHeaderPath), { recursive: true });
  fs.writeFileSync(generatedHeaderPath, toCppHeader(scriptContent), "utf8");

  console.log(
    `Generated C++ map injection header: ${path.relative(projectRoot, generatedHeaderPath)}`
  );
}

main().catch((error) => {
  const message = error instanceof Error ? error.message : String(error);
  console.error(`Error: ${message}`);
  process.exit(1);
});
